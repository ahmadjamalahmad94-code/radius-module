-- 169 — cards.extra_seconds: منحةُ وقتٍ لكلّ بطاقة
--
-- 🔴 الطلب: «بدي أقدر أضيف الوقت حتى لو منتهية — أحيانًا زبون بنظلمه وبحبّ
--    أضيفله ساعة أو ساعتين». والواجهة كانت ترفض: «تعذّر تعديل وقت البطاقة —
--    تأكّد أنّها مفعّلة (لها وقت انتهاء)».
--
-- 🔴 والسبب أعمق من الرفض: بطاقات «من أوّل اتّصال» تحسب
--        المتبقّي = أوّل اتّصال + ميزانية الحزمة − الآن
--    فـ`expire_at` **لا يدخل الحساب إطلاقًا**. أي أنّ زرّ «إضافة وقت» كان
--    يعدّل حقلًا لا يقرأه أحد: لو نجح لَما تغيّر شيء.
--
-- 🔑 `extra_seconds` منحةٌ تُضاف إلى **الميزانية نفسها**، فيحترمها كلّ
--    وضعٍ محاسبيّ (من أوّل اتّصال · بالثانية · تقويميّ) بلا استثناء، وتبقى
--    معادلة الواجهة صحيحة: المستخدم + المتبقّي = وقت البطاقة.
--
-- ⚠️ ومصيدةٌ في التصميم الساذج: منحةٌ = +delta لا تنفع بطاقةً **انتهت**.
--    نافذةٌ أُغلقت قبل ٨ ساعات + ساعةٌ واحدة = ما زالت منتهيةً بسبع، فلا
--    يشعر الزبون بشيء. لذلك تُحسب المنحة لتُنزل نهاية النافذة على
--        max(الآن, النهاية الحاليّة) + المدّة
--    فتُعطي المنتهيةَ مدّةً حقيقيّةً من الآن، ولا تسرق من بطاقةٍ حيّةٍ
--    ما تبقّى لها. (راجع grant_card_time في cards_repo.)
--
-- تراكميّة: كلّ منحةٍ تُضاف للسابقة، والسالب مسموحٌ (خصم). 0 = بلا منحة
-- ⇒ السلوك السابق حرفيًّا.
-- ════════════════════════════════════════════════════════════════════════

ALTER TABLE cards ADD COLUMN extra_seconds INTEGER NOT NULL DEFAULT 0;
