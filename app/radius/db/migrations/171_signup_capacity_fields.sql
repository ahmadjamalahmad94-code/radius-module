-- MT58 — حقلا السعة في طلب الاشتراك: الاتصالات المتزامنة + عدد المايكروتيك.
--
-- الطلب كان يجمع الهويّة وبيانات التواصل فقط، فيَضطرّ المالك لمراسلة
-- كل طالبٍ ليعرف حجمه قبل تسعيره. الآن يَذكر الطالب حاجته مباشرةً:
--   • wanted_concurrent — الاتصالات المتزامنة (نفس مقياس عروض الأسعار
--     في platform.offers، فيُقابَل الطلب بالعرض المناسب بلا حساب يدويّ).
--   • wanted_routers    — عدد أجهزة المايكروتيك المراد ربطها (يُقابل
--     حدّ max_nas في فئة الشبكة عند الإنشاء).
--
-- 0 = لم يُحدَّد (الحقلان اختياريّان — لا نُعقّد نموذجًا عموميًّا بإلزام).
-- INTEGER بافتراضٍ صفريّ: الصفوف القديمة تبقى صالحة بلا ترحيل بيانات.

ALTER TABLE signup_requests ADD COLUMN wanted_concurrent INTEGER NOT NULL DEFAULT 0;
ALTER TABLE signup_requests ADD COLUMN wanted_routers    INTEGER NOT NULL DEFAULT 0;
