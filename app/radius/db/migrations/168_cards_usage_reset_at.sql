-- 168 — cards.usage_reset_at: حدُّ «تصفير الاستخدام»
--
-- 🔴 العطب (مُشاهَدٌ على الإنتاج 2026-08-08، بطاقة 232241):
--    المشغّل يضغط «إعادة استخدام» فتظهر «تمّ تصفير استخدام البطاقة ووقت
--    بدايتها» — **ولا يتغيّر شيء**: «الوقت المتبقّي» يبقى صفرًا.
--
--    و`reset_card_usage` كان يفعل الصواب فعلًا (يمسح `first_used_at` و
--    `expire_at` و`used`). لكنّ فاحص البطاقة يشتقّ «أوّل اتّصال» بسقوطٍ
--    احتياطيٍّ إلى `MIN(acctstarttime)` من `radacct` — وهي **لا تُمسح**.
--    فيُعيد بناء البداية من جلسةٍ عمرها ساعات، ويحسب:
--        first_session + 12h − now  =  0
--    أي أنّ التصفير يُلغى في نفس اللحظة التي يقع فيها.
--
--    (السقوط الاحتياطيّ نفسه صحيحٌ ولازم: حين تُصادق FreeRADIUS محلّيًّا لا
--     يُختم `cards.first_used_at` أبدًا، فبدونه تبدو كلّ بطاقةٍ «لم تبدأ».)
--
-- 🔑 الحلّ: **حدٌّ زمنيّ** لا مسحُ سجلّات. `usage_reset_at` يسجّل لحظة
--    التصفير، وكلّ ما يُشتقّ من `radacct` يتجاهل ما قبله. فتبقى الجلسات
--    القديمة للتدقيق والمحاسبة، ويرى المشغّل بطاقةً نظيفةً كما طلب.
--
--    NULL = لم تُصفَّر قطّ ⇒ السلوك السابق حرفيًّا (بلا حدّ).
-- ════════════════════════════════════════════════════════════════════════

ALTER TABLE cards ADD COLUMN usage_reset_at TEXT;

