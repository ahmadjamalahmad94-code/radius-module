-- 186 — أولويّة العروض على مقياسٍ واحد 1–10 (موجة الإصلاح 3 — F04 N-L10)
--
-- الويب يعرض ويحفظ 1–10 (الافتراض 5، 1 = الأعلى)، والـAPI كان يفترض 100
-- ويقبل حتى 1000 ⇒ حفظ عرضٍ أُنشئ من التطبيق على الويب يعيد كتابة أولويّته
-- بصمت، وترتيب القوائم يختلف بين المسارين. التطبيع (مطابق لـ
-- plans_repo.normalize_priority):
--   • فارغ / 0 / 100 (الافتراضات القديمة) ⇒ 5،
--   • أكبر من 10 ⇒ 10، أقلّ من 1 ⇒ 1.
-- ════════════════════════════════════════════════════════════════════════
UPDATE access_plans SET priority = 5
 WHERE priority IS NULL OR priority = 0 OR priority = 100;
UPDATE access_plans SET priority = 10 WHERE priority > 10;
UPDATE access_plans SET priority = 1 WHERE priority < 1;
