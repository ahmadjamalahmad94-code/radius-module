-- منع تكرار رقم الجوال لزبائن المتجر (card_users) على مستوى المخطط.
--
-- التسجيل الذاتي من المتجر كان يفحص التكرار ثم يُدرج في خطوتين غير
-- ذرّيتين (انظر register_card_user) — نافذة سباق: طلبان متزامنان بنفس
-- الرقم يمرّان معًا فينشأ حسابان. هذا القيد يغلق النافذة ذرّيًا: قاعدة
-- البيانات ترفض الإدراج الثاني فتلتقطه الخدمة وتعيد رسالة عربية ودّية.
--
-- النطاق: فهرس فريد **جزئي** على (tenant_id, mobile) للصفوف النشطة ذات
-- رقم غير فارغ فقط — مطابقةً لدلالة الدمج في التطبيق («منع تكرار رقم
-- جوال نشط»). الصفوف بلا رقم (mobile='') أو غير النشطة (محذوفة/معطّلة)
-- لا تدخل الفهرس فلا تتصادم، ويبقى رقم محذوف قابلًا لإعادة الاستخدام.

CREATE UNIQUE INDEX IF NOT EXISTS ux_card_users_active_mobile
  ON card_users (tenant_id, mobile)
  WHERE mobile <> '' AND status = 'active';
