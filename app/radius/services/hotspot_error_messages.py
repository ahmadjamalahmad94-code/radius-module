ALLOWED_VARS = ("$(error-orig)", "$(ip)", "$(username)")


def default_messages() -> dict[str, str]:
    """قاموس {key: النص العربي الافتراضي} لكل المفاتيح القياسية."""
    return {e.key: e.default_ar for e in ERROR_KEYS}


def validate_message(text: str) -> str:
    """يفحص نص رسالة خطأ ويعيده مُطبَّعًا (يرفع ValueError بالعربية).

    القيود:
      • لا أسطر جديدة (تكسر صيغة `key = message` لكل سطر في الملف).
      • الطول ≤ MESSAGE_MAX_LEN.
    النص يُكتب في ملف نصّي يقرؤه الراوتر فقط (لا HTML) فلا حاجة
    لتهريب HTML؛ متغيّرات $(...) مسموحة ويملؤها الراوتر."""
    raw = (text or "").strip()
    if "\n" in raw or "\r" in raw:
        raise ValueError(
            "نص الرسالة يجب أن يكون سطرًا واحدًا (بلا أسطر جديدة).")
    if len(raw) > MESSAGE_MAX_LEN:
        raise ValueError(
            f"نص الرسالة يتجاوز الحد المسموح ({MESSAGE_MAX_LEN} حرفًا).")
    return raw


def _file_header() -> str:
    """ترويسة errors.txt — تعليقات تشرح المتغيّرات المتاحة، بنفس
    روح الملف الرسمي من الميكروتك (لكن بالعربية للمشغّل)."""
    return (
        "# ملف رسائل أخطاء صفحة الهوت سبوت — مُولّد من HobeRadius.\n"
        "# لا تُعدّله يدويًا على الراوتر؛ غيّر الرسائل من لوحة\n"
        "# «رسائل أخطاء الهوتسبوت» وأعد النشر.\n"
        "#\n"
        "# متغيّرات يملؤها الراوتر وقت العرض:\n"
        "#   $(error-orig) — نص الخطأ الأصلي من الهوت سبوت\n"
        "#   $(ip)         — عنوان IP للعميل\n"
        "#   $(username)   — اسم المستخدم الذي حاول الدخول\n"
        "\n")


def build_errors_txt(messages: dict[str, str], *,
                     enabled: dict[str, bool] | None = None) -> str:
    """يبني نص errors.txt الكامل بصيغة الميكروتك.

    `messages` — {error_key: نص الرسالة}. المفاتيح غير المعروفة
    تُتجاهَل؛ المفاتيح المعروفة الغائبة تسقط لنصها الافتراضي.
    `enabled` — {error_key: bool} اختياري؛ المفتاح المعطّل (False)
    لا يُكتب سطره إطلاقًا فيستخدم الراوتر نصّه الأصلي المدمج.

    الناتج: ترويسة تعليقات + سطر `key = message` لكل مفتاح مُفعّل،
    بترتيب ERROR_KEYS الثابت — نفس صيغة errors.txt الرسمية."""
    enabled = enabled or {}
    lines = [_file_header()]
    for e in ERROR_KEYS:
        if enabled.get(e.key, True) is False:
            continue
        msg = validate_message(messages.get(e.key) or e.default_ar)
        lines.append(f"{e.key} = {msg}\n")
    return "".join(lines)


